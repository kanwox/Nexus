package com.github.mihomo.android.data

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * JVM tests for the pure update-verification logic.
 *
 * These cover the rules a hostile or merely sloppy release page must not defeat:
 * sums-file parsing, ABI-aware asset selection, and fail-closed digest comparison.
 */
class UpdateVerifierTest {

    // ------------------------------------------------------------------
    // parseSha256Sums
    // ------------------------------------------------------------------

    @Test
    fun `parses standard two-space lines`() {
        val text = buildString {
            append("e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855  Nexus-arm64-v8a-release.apk\n")
            append("0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef  Nexus-x86_64-release.apk\n")
        }
        val parsed = UpdateVerifier.parseSha256Sums(text)
        assertEquals(2, parsed.size)
        assertEquals(
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
            parsed["Nexus-arm64-v8a-release.apk"]
        )
        assertEquals(
            "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef",
            parsed["Nexus-x86_64-release.apk"]
        )
    }

    @Test
    fun `handles CRLF line endings and trailing newline`() {
        val text = "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855  Nexus-arm64-v8a-release.apk\r\n" +
            "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef  Nexus-x86-release.apk\r\n"
        val parsed = UpdateVerifier.parseSha256Sums(text)
        assertEquals(2, parsed.size)
        assertTrue(parsed.containsKey("Nexus-arm64-v8a-release.apk"))
        // The \r must not leak into the filename.
        assertFalse(parsed.containsKey("Nexus-x86-release.apk\r"))
    }

    @Test
    fun `skips comments blank lines and malformed rows`() {
        val text = listOf(
            "# SHA256SUMS generated by CI",
            "",
            "not-a-digest-line",
            "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcde", // digest only, no name
            "zzzz56789abcdef0123456789abcdef0123456789abcdef0123456789abcdef  bad-hex.apk", // 'z' is not hex
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855  Nexus-arm64-v8a-release.apk"
        ).joinToString("\n")
        val parsed = UpdateVerifier.parseSha256Sums(text)
        assertEquals(mapOf("Nexus-arm64-v8a-release.apk" to
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"), parsed)
    }

    @Test
    fun `tolerates single space tab and binary-mode markers`() {
        val digest = "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        val parsed = UpdateVerifier.parseSha256Sums(
            "$digest Nexus-one-space.apk\n" +
                "$digest\tNexus-tab.apk\n" +
                "${digest}  *Nexus-binary-mode.apk\n"
        )
        assertEquals(3, parsed.size)
        assertTrue(parsed.containsKey("Nexus-one-space.apk"))
        assertTrue(parsed.containsKey("Nexus-tab.apk"))
        assertTrue(parsed.containsKey("Nexus-binary-mode.apk"))
    }

    @Test
    fun `keeps filenames that contain spaces`() {
        val digest = "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        val parsed = UpdateVerifier.parseSha256Sums("$digest  Nexus arm64 v8a release.apk\n")
        assertEquals(digest, parsed["Nexus arm64 v8a release.apk"])
    }

    @Test
    fun `missing entry returns null on lookup and empty text yields empty map`() {
        assertTrue(UpdateVerifier.parseSha256Sums("").isEmpty())
        assertTrue(UpdateVerifier.parseSha256Sums("   \n  \n").isEmpty())
        val parsed = UpdateVerifier.parseSha256Sums(
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855  other.apk\n"
        )
        assertNull(parsed["Nexus-arm64-v8a-release.apk"])
    }

    // ------------------------------------------------------------------
    // selectApkAsset
    // ------------------------------------------------------------------

    private val arm64 = "Nexus-arm64-v8a-release.apk" to "https://example/Nexus-arm64-v8a-release.apk"
    private val v7a = "Nexus-armeabi-v7a-release.apk" to "https://example/Nexus-armeabi-v7a-release.apk"
    private val x64 = "Nexus-x86_64-release.apk" to "https://example/Nexus-x86_64-release.apk"

    @Test
    fun `selects the asset matching the first supported abi`() {
        val assets = listOf(v7a, x64, arm64)
        assertEquals(arm64, UpdateVerifier.selectApkAsset(assets, listOf("arm64-v8a", "armeabi-v7a")))
    }

    @Test
    fun `falls through to the next abi when the first is missing`() {
        val assets = listOf(v7a, x64)
        assertEquals(v7a, UpdateVerifier.selectApkAsset(assets, listOf("arm64-v8a", "armeabi-v7a")))
        assertEquals(x64, UpdateVerifier.selectApkAsset(assets, listOf("x86_64")))
    }

    @Test
    fun `matching is case-insensitive`() {
        val assets = listOf("nexus-ARM64-V8A-release.APK" to "https://example/x")
        assertEquals(
            assets[0],
            UpdateVerifier.selectApkAsset(assets, listOf("arm64-v8a"))
        )
    }

    @Test
    fun `falls back to the first apk asset when no abi matches`() {
        val assets = listOf("Nexus-fallback.apk" to "https://example/fallback", "other.zip" to "https://example/z")
        assertEquals(assets[0], UpdateVerifier.selectApkAsset(assets, listOf("mips")))
    }

    @Test
    fun `non-apk assets are never selected and empty lists yield null`() {
        val assets = listOf("SHA256SUMS" to "https://example/sums", "source.zip" to "https://example/src")
        assertNull(UpdateVerifier.selectApkAsset(assets, listOf("arm64-v8a")))
        assertNull(UpdateVerifier.selectApkAsset(emptyList(), listOf("arm64-v8a")))
    }

    @Test
    fun `default abi priority prefers arm64 and degrades sanely`() {
        val assets = listOf(x64, arm64, v7a)
        assertEquals(arm64, UpdateVerifier.selectApkAsset(assets))
        // Only a non-default ABI present: still found through the default priority list.
        assertEquals(v7a, UpdateVerifier.selectApkAsset(listOf(v7a)))
    }

    // ------------------------------------------------------------------
    // verifySha256 / sha256HexOfBytes / sha256HexOfFile
    // ------------------------------------------------------------------

    @Test
    fun `digest comparison is case-insensitive`() {
        val lower = "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        assertTrue(UpdateVerifier.verifySha256(lower, lower.uppercase()))
        assertTrue(UpdateVerifier.verifySha256(lower.uppercase(), lower))
        assertFalse(UpdateVerifier.verifySha256(lower, "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"))
    }

    @Test
    fun `digest comparison fails closed on malformed input`() {
        val valid = "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        assertFalse(UpdateVerifier.verifySha256("", valid))
        assertFalse(UpdateVerifier.verifySha256(valid, ""))
        assertFalse(UpdateVerifier.verifySha256("abc123", valid)) // too short
        assertFalse(UpdateVerifier.verifySha256(valid.removeSuffix("5") + "g", valid)) // non-hex char
    }

    @Test
    fun `empty input hashes to the well-known sha-256 of nothing`() {
        assertEquals(
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
            UpdateVerifier.sha256HexOfBytes(ByteArray(0))
        )
    }

    @Test
    fun `bytes and streamed file hashing agree`() {
        // 100 KiB of pseudo-random data forces many buffer refills in the streaming path.
        val data = ByteArray(100 * 1024).also { buf ->
            var seed = 42
            for (i in buf.indices) {
                seed = seed * 1103515245 + 12345
                buf[i] = (seed ushr 16).toByte()
            }
        }
        val file = File.createTempFile("updateverifier", ".bin").apply {
            writeBytes(data)
            deleteOnExit()
        }
        val fromBytes = UpdateVerifier.sha256HexOfBytes(data)
        val fromFile = UpdateVerifier.sha256HexOfFile(file)
        assertEquals(64, fromBytes.length)
        assertEquals(fromBytes, fromFile)
        // And the parsed-sums roundtrip accepts its own digest.
        assertTrue(UpdateVerifier.verifySha256(fromFile!!, fromBytes))
    }

    @Test
    fun `streamed hash returns null for an unreadable file`() {
        assertNull(UpdateVerifier.sha256HexOfFile(File("Z:/definitely/not/a/real/path.bin")))
    }

    // ------------------------------------------------------------------
    // signaturesMatch
    // ------------------------------------------------------------------

    @Test
    fun `signature sets match regardless of order`() {
        val a = byteArrayOf(1, 2, 3)
        val b = byteArrayOf(4, 5, 6)
        assertTrue(UpdateVerifier.signaturesMatch(listOf(a, b), listOf(b, a)))
        assertTrue(UpdateVerifier.signaturesMatch(listOf(a), listOf(a.copyOf())))
    }

    @Test
    fun `signature comparison fails closed`() {
        val a = byteArrayOf(1, 2, 3)
        val b = byteArrayOf(4, 5, 6)
        val c = byteArrayOf(7)
        // A different key is rejected, including a one-byte change in the same cert.
        assertFalse(UpdateVerifier.signaturesMatch(listOf(a), listOf(b)))
        assertFalse(UpdateVerifier.signaturesMatch(listOf(a), listOf(byteArrayOf(1, 2, 4))))
        // An extra signer on the incoming side is a mismatch, not a superset pass.
        assertFalse(UpdateVerifier.signaturesMatch(listOf(a), listOf(a, c)))
        // Empty certificate lists mean extraction failed — never a pass.
        assertFalse(UpdateVerifier.signaturesMatch(emptyList(), listOf(a)))
        assertFalse(UpdateVerifier.signaturesMatch(listOf(a), emptyList()))
    }
}
